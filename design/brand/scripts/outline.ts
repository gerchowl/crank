// pnpm outline — outlines "CRANK" from the vendored OFL font (fonts/, BRAND.md §Type) into
// src/glyphs.ts, so neither the app nor assets/brand/*.svg depend on the font at runtime.
// Coordinates are font units, y down, baseline at y = 0. Kerning comes from the font's GPOS/kern.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import opentype from "opentype.js";

const FONT = "Barlow-Bold.ttf";
const TEXT = "CRANK";

const buf = readFileSync(fileURLToPath(new URL(`../fonts/${FONT}`, import.meta.url)));
const font = opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));
const upm = font.unitsPerEm;
const capHeight = (font.tables.os2 as unknown as { sCapHeight: number }).sCapHeight;
const glyphs = font.stringToGlyphs(TEXT).map((g, i, all) => {
  const next = all[i + 1];
  const box = g.getBoundingBox();
  return {
    char: TEXT[i],
    d: g.getPath(0, 0, upm).toPathData(1),
    advance: g.advanceWidth ?? 0,
    kern: next ? font.getKerningValue(g, next) : 0,
    xMin: box.x1,
    xMax: box.x2,
  };
});

const out = `// GENERATED by scripts/outline.ts from fonts/${FONT} (SIL OFL 1.1, fonts/OFL.txt). Do not edit.
export const FONT = ${JSON.stringify(FONT)};
export const UPM = ${upm};
export const CAP_HEIGHT = ${capHeight};
export const GLYPHS = ${JSON.stringify(glyphs, null, 2)} as const;
`;
writeFileSync(fileURLToPath(new URL("../src/glyphs.ts", import.meta.url)), out);
console.log(`outlined ${TEXT} from ${FONT}: upm ${upm}, cap height ${capHeight}`);
