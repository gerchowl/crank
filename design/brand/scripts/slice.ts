// Part of `pnpm outline`: builds A · Slice as true outlines with boolean ops (paper.js) into src/slice.ts —
// plain filled paths with the 12° shear baked in, no clipPath, no ids, nothing live (BRAND.md §Construction).
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import paper from "paper";
import { GLYPHS } from "../src/glyphs.ts";
import { H, SLICE, layout, n, tAxis, tSlant } from "../src/geometry.ts";

paper.setup(new paper.Size(1, 1));
const P = 2; // decimals in the output
const { xs, left } = layout();
const { g, cuts, lead } = SLICE;
const shear = new paper.Matrix(1, 0, -tSlant, 1, 0, 0); // x' = x − y·tan 12°

const glyph = (i: number) => {
  const p = new paper.CompoundPath(GLYPHS[i]!.d);
  p.translate(new paper.Point(xs[i]!, 0));
  p.transform(shear);
  return p;
};
const rect = (x0: number, y0: number, x1: number, y1: number) => new paper.Path.Rectangle(new paper.Rectangle(x0, y0, x1 - x0, y1 - y0));
// getPathData(matrix, precision) exists at runtime but is missing from paper's typings.
const data = (p: paper.PathItem) => (p as unknown as { getPathData(m: paper.Matrix, precision: number): string }).getPathData(new paper.Matrix(), P);
const unite = (items: paper.PathItem[]) => items.slice(1).reduce((a, b) => a.unite(b, { insert: false }), items[0]!);

const W = 6000; // wider than anything we draw
const bands = unite(cuts.map((y) => rect(-W, y - g / 2, W, y + g / 2)));
const uncut = GLYPHS.map((_, i) => glyph(i));
const letters = uncut.map((p) => p.subtract(bands, { insert: false }));

// Speed lines. Left end: a 50° chamfer whose bottom corner sits on the axis line x = left − lead − y/tan 50°.
// Right end: the C's own outline moved left by g, so the gap to the letter is g at every height of the bar.
const cShifted = uncut[0]!.clone({ insert: false });
cShifted.translate(new paper.Point(-g, 0));
const starts: number[] = [];
const bars = cuts.map((y) => {
  const top = y - g / 2;
  const bot = y + g / 2;
  const x0 = left - lead - bot / tAxis; // on the 50° line through (left − lead, 0)
  starts.push(x0);
  const deep = left + 70 - top * tSlant; // well inside the C's stem at this height
  const bar = new paper.Path({ segments: [[x0, bot], [x0 + g / tAxis, top], [deep, top], [deep, bot]], closed: true, insert: false });
  return bar.subtract(cShifted, { insert: false });
});

const all = unite([...letters, ...bars]).bounds;
const word = unite(uncut).bounds;
const pad = 0.1 * H;
const box = (b: paper.Rectangle) => [n(b.x - pad), n(b.y - pad), n(b.width + 2 * pad), n(b.height + 2 * pad)] as const;

const out = `// GENERATED by scripts/slice.ts (pnpm outline). Do not edit. Construction: src/geometry.ts SLICE, BRAND.md.
export const SLICE_ART = ${JSON.stringify(
  {
    letters: letters.map(data),
    bars: bars.map(data),
    box: box(all),
    focus: n(word.center.x), // optical centre = the letters, not the trailing lines
    starts: starts.map(n),
    small: uncut.map(data),
    smallBox: box(word),
  },
  null,
  2,
)} as const;
`;
writeFileSync(fileURLToPath(new URL("../src/slice.ts", import.meta.url)), out);
console.log(`slice: line starts ${starts.map(n).join(", ")}; Δx/Δy = ${n((starts[1]! - starts[0]!) / (cuts[0]! - cuts[1]!))} (cot 50° = ${n(1 / tAxis)})`);
