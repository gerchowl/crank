// Part of `pnpm outline`: geometry for F · Spin-up (BRAND.md §F · Spin-up) into src/spin-art.ts (GENERATED).
//  - `crank`: the mark's arms + chainring as one outline (holes for the BB and the pedal spindle), mark units,
//    hub at 0,0 — exactly assets/icon/logo.svg minus the ring and the squircle, split at the ring's outer
//    radius into `crank` (inside) and `tip` (the pedal end beyond it). `ghost`: the same without the
//    pedal hole and clipped to the ring's outer radius, for the blur copies (a translucent pedal eye beyond
//    the ring reads as a bead; a tip past the ring as a fan blade).
//  - `c`: the wordmark's C (uncut, sheared — the small-form outline A's C is cut from), sampled on the outline
//    in four runs that a ring can be matched to: outer arc, top terminal face, inner arc, bottom terminal face.
//    Every vertex lies on the true outline; the run fails if a chord strays from it by more than MAX_DEV units.
//  - `lefts`: x of the left ink edge of R A N K at mid cap height, as set (sheared): once the gliding ring has
//    passed it, the letter is clear of the ring.
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import paper from "paper";
import { GLYPHS } from "../src/glyphs.ts";
import { AXIS, H, layout, n, tSlant } from "../src/geometry.ts";

paper.setup(new paper.Size(1, 1));
const DEG = Math.PI / 180;
/** Vertices per run: outer, top face, inner, bottom face. */
const RUNS = [320, 48, 200, 48] as const;
/** Largest allowed distance between a chord and the outline: 0.5 units ≈ 0.1 px at the 820 px start screen. */
const MAX_DEV = 0.5;

// --- the crank (logo.svg: arms 310 / 420 on the 50° axis, chainring r 108, BB hole r 56, pedal hole r 26) ---
const arm = (len: number, deg: number) => {
  const p = new paper.Path({ pathData: `M0 -59L${len} -39A39 39 0 0 1 ${len} 39L0 59Z`, insert: false });
  p.rotate(deg, new paper.Point(0, 0));
  return p;
};
const disc = (r: number, x = 0, y = 0) => new paper.Path.Circle({ center: [x, y], radius: r, insert: false });
const pedal = [420 * Math.cos(-AXIS * DEG), 420 * Math.sin(-AXIS * DEG)] as const;
const body = arm(310, -230)
  .unite(arm(420, -AXIS), { insert: false })
  .unite(disc(108), { insert: false })
  .subtract(disc(56), { insert: false });
const crank = body.subtract(disc(26, ...pedal), { insert: false });
const ghost = body.intersect(disc(412.5), { insert: false });
// The crank split at the ring's outer radius: the tip (pedal end + eye) moves fastest, so it blurs out first.
const crankIn = crank.intersect(disc(412.5), { insert: false });
const tip = crank.subtract(disc(412.5), { insert: false });

// --- the C: the same transform the wordmark applies (x' = x − y·tan 12°, at the C's origin) ---
const { xs } = layout();
const c = new paper.Path({ pathData: GLYPHS[0].d, insert: false });
c.translate(new paper.Point(xs[0]!, 0));
const shear = new paper.Matrix(1, 0, -tSlant, 1, 0, 0);
// Terminal corners of Barlow's C (outline vertices, font units): the faces run between them.
const corners = [
  [566, -225], // bottom outer
  [566, -477], // top outer
  [425, -470], // top inner
  [425, -229], // bottom inner
].map(([x, y]) => c.getNearestLocation(new paper.Point(x! + xs[0]!, y!)).offset);
c.transform(shear);
const len = c.length;
const runs = corners.map((from, i) => {
  const to = corners[(i + 1) % 4]!;
  const span = (to - from + len) % len;
  const count = RUNS[i]!;
  const pts: [number, number][] = [];
  let dev = 0;
  for (let k = 0; k < count; k++) {
    const at = (o: number) => c.getPointAt((from + (span * o) / count) % len);
    const a = at(k);
    const b = at(k + 1);
    // distance from the outline between the two vertices to the chord a→b
    const ab = b.subtract(a);
    for (const f of [0.25, 0.5, 0.75])
      dev = Math.max(dev, ab.length ? Math.abs(ab.cross(at(k + f).subtract(a))) / ab.length : 0);
    pts.push([n(a.x), n(a.y)]);
  }
  if (dev > MAX_DEV) throw new Error(`C run ${i}: chord deviation ${dev.toFixed(2)} > ${MAX_DEV} units`);
  return { pts, dev };
});

const lefts = GLYPHS.slice(1).map((g, i) => n(xs[i + 1]! + g.xMin + (H / 2) * tSlant));

const data = (p: paper.PathItem) => (p as unknown as { getPathData(m: paper.Matrix, precision: number): string }).getPathData(new paper.Matrix(), 2);
const out = `// GENERATED by scripts/spin.ts (pnpm outline). Do not edit. Design: BRAND.md §F · Spin-up.
export const SPIN_ART = ${JSON.stringify({ crank: data(crankIn), tip: data(tip), ghost: data(ghost), c: runs.map((r) => r.pts), lefts })} as const;
`;
writeFileSync(fileURLToPath(new URL("../src/spin-art.ts", import.meta.url)), out);
console.log(`spin: C sampled ${RUNS.join("/")} vertices; max chord deviation ${n(Math.max(...runs.map((r) => r.dev)))} units (≤ ${MAX_DEV})`);
