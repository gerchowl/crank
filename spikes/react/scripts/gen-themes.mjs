// Generates src/theme/tokens.css from OKLCH ramps and validates every data palette with the
// dataviz validator (vendored as ./validate_palette.js). Run: node scripts/gen-themes.mjs
// Exits non-zero if any hard check fails, so a bad preset can't ship.
import { writeFileSync } from "node:fs";
import { validate, validateOrdinal } from "./validate_palette.js";

// ---------- OKLCH -> sRGB hex (with chroma reduction until in gamut) ----------
function oklchToRgb(L, C, h) {
  const a = C * Math.cos((h * Math.PI) / 180);
  const b = C * Math.sin((h * Math.PI) / 180);
  const l_ = L + 0.3963377774 * a + 0.2158037573 * b;
  const m_ = L - 0.1055613458 * a - 0.0638541728 * b;
  const s_ = L - 0.0894841775 * a - 1.291485548 * b;
  const l = l_ ** 3, m = m_ ** 3, s = s_ ** 3;
  const lin = [
    4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s,
    -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s,
    -0.0041960863 * l - 0.7034186147 * m + 1.707614701 * s,
  ];
  return lin.map((x) => (x <= 0.0031308 ? 12.92 * x : 1.055 * Math.pow(x, 1 / 2.4) - 0.055));
}
function oklch(L, C, h) {
  let c = C;
  for (;;) {
    const rgb = oklchToRgb(L, c, h);
    if (rgb.every((v) => v >= -1e-4 && v <= 1 + 1e-4) || c <= 0) {
      return "#" + rgb.map((v) => Math.round(Math.min(1, Math.max(0, v)) * 255).toString(16).padStart(2, "0")).join("");
    }
    c -= 0.005;
  }
}
const ramp = (n, Lfrom, Lto, C, h) => Array.from({ length: n }, (_, i) => oklch(Lfrom + ((Lto - Lfrom) * i) / (n - 1), C, h));

// ---------- fixed parts (from the dataviz reference palette) ----------
const SURF = {
  dark: { s0: "#0d0d0d", s1: "#1a1a19", s2: "#262624", ink1: "#f0efec", ink2: "#c3c2b7", muted: "#898781", border: "#383835", grid: "#2c2c2a" },
  light: { s0: "#f2f1ed", s1: "#fcfcfb", s2: "#ebeae5", ink1: "#0b0b0b", ink2: "#52514e", muted: "#76746f", border: "#c3c2b7", grid: "#e1e0d9" },
};
// Fixed series identity: power, hr, cadence, dfa, torque (slots 1–5), never re-assigned by theme.
const SERIES = {
  light: ["#2a78d6", "#eb6834", "#1baf7a", "#eda100", "#e87ba4"],
  dark: ["#3987e5", "#d95926", "#199e70", "#c98500", "#d55181"],
};
const STATUS = { good: "#0ca30c", warning: "#fab219", serious: "#ec835a", critical: "#d03b3b" };
const DIVERGING = { light: ["#2a78d6", "#c3c2b7", "#e34948"], dark: ["#3987e5", "#5a5955", "#e66767"] };
// Classic zones (opt-in, not CVD-safe): grey, blue, green, yellow, orange, red, purple.
const CLASSIC = {
  light: ["#8a94a6", "#3b82f6", "#22c55e", "#eab308", "#f97316", "#ef4444", "#a855f7"],
  dark: ["#6b7280", "#3b82f6", "#22c55e", "#eab308", "#f97316", "#ef4444", "#a855f7"],
};

// ---------- presets: accent hue/chroma, zone hue/chroma, fatigue hue/chroma ----------
const PRESETS = {
  graphite: { accent: [258, 0.02], zone: [258, 0.018], fatigue: [255, 0.13] },
  ocean: { accent: [255, 0.15], zone: [255, 0.14], fatigue: [75, 0.15] },
  ember: { accent: [40, 0.17], zone: [28, 0.17], fatigue: [190, 0.11], critical: "#c2369b" },
};

// Zone ramp: Z1 → Z7 is light→dark on light surfaces and dark→light on dark (always "more = more ink").
const ZONE_L = { light: [0.75, 0.33], dark: [0.47, 0.91] };
const FATIGUE_L = { light: [0.71, 0.38], dark: [0.47, 0.85] };

let failed = false;
const report = [];
function check(name, res) {
  const bad = res.report.filter(([, s]) => s === false || s === "fail");
  report.push(`${res.ok ? "PASS" : "FAIL"}  ${name}${bad.length ? "  " + bad.map((r) => r[0] + ": " + r[2]).join("; ") : ""}`);
  if (!res.ok) failed = true;
}

let css = `/* GENERATED by scripts/gen-themes.mjs — do not edit by hand. */\n`;
for (const [name, p] of Object.entries(PRESETS)) {
  for (const mode of ["dark", "light"]) {
    const s = SURF[mode];
    const zones = ramp(7, ZONE_L[mode][0], ZONE_L[mode][1], p.zone[1], p.zone[0]);
    const fatigue = ramp(5, FATIGUE_L[mode][0], FATIGUE_L[mode][1], p.fatigue[1], p.fatigue[0]);
    const accent = oklch(mode === "dark" ? 0.68 : 0.52, p.accent[1], p.accent[0]);
    const accentSoft = oklch(mode === "dark" ? 0.32 : 0.92, p.accent[1] * 0.45, p.accent[0]);
    const accentInk = mode === "dark" ? "#0b0b0b" : "#ffffff";
    check(`${name}/${mode} zones`, validateOrdinal(zones, { mode, surface: s.s1 }));
    check(`${name}/${mode} fatigue`, validateOrdinal(fatigue, { mode, surface: s.s1 }));
    const series = SERIES[mode];
    check(`${name}/${mode} series (adjacent, 5)`, validate(series, { mode, surface: s.s1 }));
    check(`${name}/${mode} series (all pairs, first 3)`, validate(series.slice(0, 3), { mode, surface: s.s1, pairs: "all" }));
    const sel = `:root[data-theme="${name}"]`;
    const body = [
      `color-scheme: ${mode};`,
      `--surface-0: ${s.s0}; --surface-1: ${s.s1}; --surface-2: ${s.s2};`,
      `--ink-primary: ${s.ink1}; --ink-secondary: ${s.ink2}; --ink-muted: ${s.muted};`,
      `--border: ${s.border}; --grid: ${s.grid}; --focus: ${accent};`,
      `--accent: ${accent}; --accent-ink: ${accentInk}; --accent-soft: ${accentSoft};`,
      `--series-power: ${series[0]}; --series-hr: ${series[1]}; --series-cadence: ${series[2]}; --series-dfa: ${series[3]}; --series-torque: ${series[4]};`,
      `--target: ${s.ink2};`,
      zones.map((z, i) => `--zone-${i + 1}: ${z};`).join(" "),
      zones.map((z, i) => `--seq-${i + 1}: ${z};`).join(" "),
      fatigue.map((z, i) => `--fatigue-${i + 1}: ${z};`).join(" "),
      `--div-neg: ${DIVERGING[mode][0]}; --div-mid: ${DIVERGING[mode][1]}; --div-pos: ${DIVERGING[mode][2]};`,
      `--status-good: ${STATUS.good}; --status-warning: ${STATUS.warning}; --status-serious: ${STATUS.serious}; --status-critical: ${p.critical ?? STATUS.critical};`,
    ].map((l) => "  " + l).join("\n");
    if (mode === "dark") {
      // explicit dark, plus Auto (no data-mode or data-mode="auto") following the OS
      css += `${sel}[data-mode="dark"] {\n${body}\n}\n`;
      css += `@media (prefers-color-scheme: dark) {\n  ${sel}:where(:not([data-mode="light"])) {\n${body.replace(/^/gm, "  ")}\n  }\n}\n`;
    } else {
      css += `${sel}[data-mode="light"] {\n${body}\n}\n`;
      css += `@media (prefers-color-scheme: light) {\n  ${sel}:where(:not([data-mode="dark"])) {\n${body.replace(/^/gm, "  ")}\n  }\n}\n`;
    }
  }
}
for (const mode of ["dark", "light"]) {
  const z = CLASSIC[mode];
  const sel = mode === "dark" ? `[data-mode="dark"]` : `[data-mode="light"]`;
  const vars = z.map((c, i) => `--zone-${i + 1}: ${c};`).join(" ");
  css += `:root[data-zones="classic"]${sel} { ${vars} }\n`;
  css += `@media (prefers-color-scheme: ${mode}) { :root[data-zones="classic"]:where([data-mode="auto"]) { ${vars} } }\n`;
}

writeFileSync(new URL("../src/theme/tokens.css", import.meta.url), css);
writeFileSync(new URL("../src/theme/palette-report.txt", import.meta.url), report.join("\n") + "\n");
console.log(report.join("\n"));
if (failed) {
  console.error("\npalette validation FAILED");
  process.exit(1);
}
