// Generates src/theme/palette.css: zone/fatigue ramps per preset × mode, built in OKLCH and
// validated with the dataviz validator (ordinal checks for ramps, categorical for series).
// Run: node scripts/gen-palette.mjs   (exits 1 if any validated set fails)
import { writeFileSync } from "node:fs";
import { validate, validateOrdinal } from "./validate_palette.js";

const SURFACE = { light: "#fcfcfb", dark: "#1a1a19" };

// ---- OKLCH → sRGB hex with chroma reduction until in gamut ----
function oklchToLinear(L, C, h) {
  const a = C * Math.cos((h * Math.PI) / 180);
  const b = C * Math.sin((h * Math.PI) / 180);
  const l_ = L + 0.3963377774 * a + 0.2158037573 * b;
  const m_ = L - 0.1055613458 * a - 0.0638541728 * b;
  const s_ = L - 0.0894841775 * a - 1.291485548 * b;
  const l = l_ ** 3, m = m_ ** 3, s = s_ ** 3;
  return [
    4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s,
    -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s,
    -0.0041960863 * l - 0.7034186147 * m + 1.707614701 * s,
  ];
}
const toS = (c) => (c <= 0.0031308 ? 12.92 * c : 1.055 * c ** (1 / 2.4) - 0.055);
function oklch(L, C, h) {
  let c = C;
  for (;;) {
    const rgb = oklchToLinear(L, c, h);
    if (rgb.every((v) => v >= -1e-4 && v <= 1 + 1e-4) || c <= 0) {
      return "#" + rgb.map((v) => Math.round(Math.max(0, Math.min(1, toS(Math.max(0, v)))) * 255).toString(16).padStart(2, "0")).join("");
    }
    c -= 0.002;
  }
}

/** n-step ramp; light mode runs light→dark (Z1 lightest), dark mode dark→light. */
function ramp(h, C, n, mode) {
  const [hiL, loL] = mode === "light" ? [0.76, 0.3] : [0.92, 0.44];
  const steps = [];
  for (let i = 0; i < n; i++) {
    const L = hiL - ((hiL - loL) * i) / (n - 1);
    // chroma peaks mid-ramp so the pale/deep ends stay in gamut and readable
    const c = C * (0.55 + 0.45 * Math.sin((Math.PI * (i + 0.5)) / n));
    steps.push(oklch(L, c, h));
  }
  return mode === "light" ? steps : steps.reverse();
}

const HUES = {
  blue: { h: 255, C: 0.15 },
  grey: { h: 260, C: 0.012 },
  red: { h: 27, C: 0.19 },
  amber: { h: 70, C: 0.15 },
  teal: { h: 190, C: 0.11 },
};
const PRESETS = {
  graphite: { zone: "grey", fatigue: "blue", accent: { light: "#52514e", dark: "#c3c2b7" }, accentInk: { light: "#ffffff", dark: "#111110" } },
  ocean: { zone: "blue", fatigue: "amber", accent: { light: "#2a6fd0", dark: "#5598e7" }, accentInk: { light: "#ffffff", dark: "#0b1a2e" } },
  ember: { zone: "red", fatigue: "teal", accent: { light: "#c8461f", dark: "#ee7a4c" }, accentInk: { light: "#ffffff", dark: "#2a0f05" } },
};

// Fixed series identity (reference palette, slots 1–5), stepped per mode.
const SERIES = {
  light: { power: "#2a78d6", hr: "#eb6834", cadence: "#1baf7a", dfa: "#eda100", torque: "#e87ba4" },
  dark: { power: "#3987e5", hr: "#d95926", cadence: "#199e70", dfa: "#c98500", torque: "#d55181" },
};
// Opt-in "classic" rainbow zones — not CVD safe (flagged in the UI).
const CLASSIC = ["#8a94a6", "#3b82f6", "#22c55e", "#eab308", "#f97316", "#ef4444", "#a855f7"];

let failed = false;
const check = (label, result) => {
  const bad = result.report.filter(([, s]) => s === false || s === "fail");
  if (!result.ok) failed = true;
  console.log(`${result.ok ? "PASS" : "FAIL"}  ${label}${bad.length ? "  " + JSON.stringify(bad) : ""}`);
};

let css = "/* GENERATED by scripts/gen-palette.mjs — do not edit by hand. */\n";
for (const mode of ["light", "dark"]) {
  const s = SERIES[mode];
  check(`series ${mode} (adjacent, 5 slots)`, validate(Object.values(s), { mode, surface: SURFACE[mode] }));
  check(`series ${mode} (all-pairs, power/hr/cadence)`, validate([s.power, s.hr, s.cadence], { mode, surface: SURFACE[mode], pairs: "all" }));
  for (const [name, p] of Object.entries(PRESETS)) {
    const z = ramp(HUES[p.zone].h, HUES[p.zone].C, 7, mode);
    const f = ramp(HUES[p.fatigue].h, HUES[p.fatigue].C, 5, mode);
    check(`${name} ${mode} zones (${p.zone})`, validateOrdinal(z, { mode, surface: SURFACE[mode] }));
    check(`${name} ${mode} fatigue (${p.fatigue})`, validateOrdinal(f, { mode, surface: SURFACE[mode] }));
    const sel = `:root[data-theme="${name}"][data-mode="${mode}"]`;
    const auto = `:root[data-theme="${name}"]:where([data-mode="auto"])`;
    const body =
      `  --accent: ${p.accent[mode]}; --accent-ink: ${p.accentInk[mode]};\n` +
      `  --accent-soft: color-mix(in oklab, ${p.accent[mode]} 22%, transparent);\n` +
      `  --series-power: ${s.power}; --series-hr: ${s.hr}; --series-cadence: ${s.cadence}; --series-dfa: ${s.dfa}; --series-torque: ${s.torque};\n` +
      z.map((c, i) => `  --zone-${i + 1}: ${c};`).join("\n") + "\n" +
      z.map((c, i) => `  --seq-${i + 1}: ${c};`).join("\n") + "\n" +
      f.map((c, i) => `  --fatigue-${i + 1}: ${c};`).join("\n") + "\n" +
      (name === "ember" ? `  --status-critical: ${mode === "light" ? "#b8338f" : "#e05ab0"};\n` : "");
    css += `${sel} {\n${body}}\n`;
    if (mode === "dark") css += `@media (prefers-color-scheme: dark) {\n  ${auto} {\n${body.replace(/^/gm, "  ")}  }\n}\n`;
    else css += `${auto} {\n${body}}\n`;
  }
}
css += `:root[data-zones="classic"] {\n${CLASSIC.map((c, i) => `  --zone-${i + 1}: ${c};`).join("\n")}\n}\n`;

writeFileSync(new URL("../src/theme/palette.css", import.meta.url), css);
console.log(failed ? "palette: FAILED" : "palette: all validated sets pass → src/theme/palette.css");
process.exit(failed ? 1 : 0);
