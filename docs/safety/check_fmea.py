#!/usr/bin/env python3
"""Validator and renderer of the FMEA (docs/safety/FMEA.md, docs/safety/fmea.toml; #255).

Stdlib only (tomllib, Python >= 3.11). fmea.toml is the source; FMEA.md carries the rendered
table between the `fmea:table` markers. The check fails unless:

* the schema holds: [meta] lists the phases and the severity scale S1-S4, every [[row]] has
  exactly the known keys, a known phase and severity, non-empty strings, and
  wanted.{trainer,engine,ui};
* ids are unique and match FM-<AREA>-<NN>;
* every row has a guard (an ADR or DESIGN section, or a decided issue) and a test or an issue:
  status `guarded` needs `test` (path::name, one or more); `pending-merge` needs `test` and the
  `pr` that adds it; `missing` needs `test = "missing"` and an `issue`;
* every cited test exists: the file is in the repo and defines `fn <name>` (.rs) or
  `def <name>` (.py); pending-merge tests are checked against the PR when it merges (the row
  flips to `guarded`), not here;
* a wanted field is "UNDECIDED" only with a `question` that FMEA.md's "Open questions" lists;
* the table in FMEA.md equals the one rendered from fmea.toml.

A built-in self-test mutates a valid row once per rule and asserts that each mutation fails.

Run: python3 docs/safety/check_fmea.py [repo-root]          (exit 0 = all checks pass)
     python3 docs/safety/check_fmea.py --write [repo-root]  (re-render the table into FMEA.md)
CI runs the check as the `fmea` flake check; `just fmea` locally.
"""
from __future__ import annotations

import copy
import re
import sys
import tomllib
from pathlib import Path

PHASES = ["start", "ramp", "steady", "released", "free_sim", "paused", "finishing"]
SEVERITIES = {"S1": "injury or strain", "S2": "ride lost", "S3": "data loss", "S4": "cosmetic"}
STATUSES = {"guarded", "pending-merge", "missing"}
ROW_KEYS = {"id", "failure_mode", "cause", "phase", "fault_plan", "severity", "detection", "guard",
            "status", "test", "issue", "pr", "question", "note", "wanted"}
REQUIRED = {"id", "failure_mode", "cause", "phase", "fault_plan", "severity", "detection", "guard",
            "status", "test", "wanted"}
WANTED_KEYS = {"trainer", "engine", "ui"}
ID_RE = re.compile(r"^FM-[A-Z]+-\d{2}$")
GUARD_RE = re.compile(r"(ADR-000\d §[\d.]+|DESIGN §[\d.]+|#\d+)")
TEST_RE = re.compile(r"^([\w./-]+\.(rs|py))::(\w+)$")
BEGIN, END = "<!-- fmea:table:begin (generated by check_fmea.py --write) -->", "<!-- fmea:table:end -->"


def tests_of(row):
    t = row.get("test")
    return [t] if isinstance(t, str) else list(t or [])


def check_test(root: Path, ref: str):
    m = TEST_RE.match(ref)
    if not m:
        return f"test {ref!r} is not <path>::<fn>"
    path, ext, name = m.groups()
    f = root / path
    if not f.is_file():
        return f"test file {path} does not exist"
    pat = rf"\bfn {name}\b" if ext == "rs" else rf"^\s*def {name}\b"
    if not re.search(pat, f.read_text(encoding="utf-8"), re.M):
        return f"{path} defines no {'fn' if ext == 'rs' else 'def'} {name}"
    return None


def open_questions(md: str):
    if "## Open questions" not in md:
        return set()
    return set(re.findall(r"^\*\*(Q\d+)\*\*", md.split("## Open questions", 1)[1], re.M))


def validate(data: dict, md: str, root: Path, grep: bool = True):
    errs = []
    meta = data.get("meta", {})
    if meta.get("phases") != PHASES:
        errs.append(f"meta.phases must be {PHASES}")
    if meta.get("severity") != SEVERITIES:
        errs.append(f"meta.severity must be {SEVERITIES}")
    questions = open_questions(md)
    seen = set()
    rows = data.get("row", [])
    if not rows:
        errs.append("no [[row]]")
    for i, r in enumerate(rows):
        rid = r.get("id", f"row[{i}]")
        e = lambda msg: errs.append(f"{rid}: {msg}")  # noqa: E731
        if set(r) - ROW_KEYS:
            e(f"unknown keys {sorted(set(r) - ROW_KEYS)}")
        if REQUIRED - set(r):
            e(f"missing keys {sorted(REQUIRED - set(r))}")
            continue
        if not ID_RE.match(r["id"]):
            e("id must match FM-<AREA>-<NN>")
        if r["id"] in seen:
            e("duplicate id")
        seen.add(r["id"])
        for k in ("failure_mode", "cause", "fault_plan", "detection", "guard"):
            if not isinstance(r[k], str) or not r[k].strip():
                e(f"{k} must be a non-empty string")
        if r["phase"] not in PHASES:
            e(f"phase {r['phase']!r} not in {PHASES}")
        if r["severity"] not in SEVERITIES:
            e(f"severity {r['severity']!r} not in {sorted(SEVERITIES)}")
        if isinstance(r["guard"], str) and not GUARD_RE.search(r["guard"]):
            e("guard cites no ADR-000N §x, DESIGN §x or #issue")
        w = r["wanted"]
        if not isinstance(w, dict) or set(w) != WANTED_KEYS:
            e(f"wanted must have exactly {sorted(WANTED_KEYS)}")
        else:
            for k, v in w.items():
                if not isinstance(v, str) or not v.strip():
                    e(f"wanted.{k} must be a non-empty string")
            if any(v == "UNDECIDED" for v in w.values()):
                q = r.get("question")
                if not q:
                    e("UNDECIDED wanted needs a question")
                elif q not in questions:
                    e(f"question {q} is not in FMEA.md's Open questions")
        st, tests = r["status"], tests_of(r)
        if st not in STATUSES:
            e(f"status {st!r} not in {sorted(STATUSES)}")
        elif st == "missing":
            if r["test"] != "missing":
                e('status missing needs test = "missing"')
            if not isinstance(r.get("issue"), int):
                e("status missing needs an issue number")
        else:
            if not tests or "missing" in tests:
                e(f"status {st} needs test path::name")
            if st == "pending-merge" and not isinstance(r.get("pr"), int):
                e("status pending-merge needs the pr that adds the test")
            if grep and st == "guarded":
                for t in tests:
                    if (msg := check_test(root, t)):
                        e(msg)
    table = render(data)
    if BEGIN not in md or END not in md:
        errs.append("FMEA.md lacks the fmea:table markers")
    elif md.split(BEGIN, 1)[1].split(END, 1)[0].strip() != table.strip():
        errs.append("FMEA.md table differs from fmea.toml (run check_fmea.py --write)")
    return errs


def cell(s) -> str:
    return str(s).replace("|", "\\|").replace("\n", " ")


def render(data: dict) -> str:
    rows = data.get("row", [])
    count = lambda key, vals: ", ".join(f"{sum(r.get(key) == v for r in rows)} {v}" for v in vals)  # noqa: E731
    out = [f"{len(rows)} rows: {count('severity', sorted(SEVERITIES))}; "
           f"{count('status', ['guarded', 'pending-merge', 'missing'])}.", ""]
    for phase in PHASES:
        in_phase = [r for r in rows if r.get("phase") == phase]
        if not in_phase:
            continue
        out += [f"### Phase `{phase}`", "",
                "| id | sev | failure mode · cause | fault plan | wanted: trainer | wanted: engine | "
                "wanted: UI | detection | guard | test |",
                "|---|---|---|---|---|---|---|---|---|---|"]
        for r in in_phase:
            w = r.get("wanted", {})
            st = r.get("status")
            if st == "missing":
                test = f"**missing** (#{r.get('issue')})"
            else:
                test = "<br>".join(f"`{x}`" for x in tests_of(r))
                if st == "pending-merge":
                    test = f"pending-merge (#{r.get('pr')}): {test}"
                if r.get("issue"):
                    test += f" · #{r['issue']}"
            if r.get("question"):
                test += f" · {r['question']}"
            out.append("| " + " | ".join(cell(x) for x in [
                r.get("id"), r.get("severity"), f"**{r.get('failure_mode')}** · {r.get('cause')}",
                r.get("fault_plan"), w.get("trainer"), w.get("engine"), w.get("ui"),
                r.get("detection"), r.get("guard"), test]) + " |")
        out.append("")
    return "\n".join(out)


def self_test(data: dict, md: str, root: Path):
    """Each mutation must make the check fail (the rules above are live, not decorative)."""
    base = next(r for r in data["row"] if r["status"] == "guarded")
    def mut(f):
        d = copy.deepcopy(data)
        r = next(x for x in d["row"] if x["id"] == base["id"])
        f(d, r)
        return d
    cases = {
        "duplicate id": lambda d, r: d["row"].append(copy.deepcopy(r)),
        "bad phase": lambda d, r: r.update(phase="cruise"),
        "bad severity": lambda d, r: r.update(severity="S5"),
        "no guard": lambda d, r: r.update(guard="common sense"),
        "missing without issue": lambda d, r: (r.update(status="missing", test="missing"), r.pop("issue", None)),
        "test not in repo": lambda d, r: r.update(test="crates/crank-engine/tests/scenarios.rs::no_such_test_xyz"),
        "undecided without question": lambda d, r: (r["wanted"].update(ui="UNDECIDED"), r.pop("question", None)),
        "unknown key": lambda d, r: r.update(extra="x"),
        "scale changed": lambda d, r: d["meta"]["severity"].update(S4="trivial"),
    }
    failed = []
    for name, f in cases.items():
        d = mut(f)
        md2 = md.replace(render(data).strip(), render(d).strip())
        if not validate(d, md2, root):
            failed.append(name)
    stale = md.replace(render(data).strip(), render(mut(lambda d, r: r.update(cause="x"))).strip())
    if not validate(data, stale, root, grep=False):
        failed.append("table drift")
    return [f"self-test: mutation '{n}' was not caught" for n in failed]


def main(argv):
    write = "--write" in argv
    args = [a for a in argv if a != "--write"]
    root = Path(args[0]) if args else Path(__file__).resolve().parents[2]
    toml_p, md_p = root / "docs/safety/fmea.toml", root / "docs/safety/FMEA.md"
    data = tomllib.loads(toml_p.read_text(encoding="utf-8"))
    md = md_p.read_text(encoding="utf-8")
    if write:
        if BEGIN not in md or END not in md:
            sys.exit("fmea: FMEA.md lacks the fmea:table markers")
        head, rest = md.split(BEGIN, 1)
        md = f"{head}{BEGIN}\n\n{render(data)}\n{END}{rest.split(END, 1)[1]}"
        md_p.write_text(md, encoding="utf-8")
    errs = validate(data, md, root)
    if not errs:
        errs = self_test(data, md, root)
    if errs:
        print("\n".join(f"fmea: {x}" for x in errs), file=sys.stderr)
        return 1
    rows = data["row"]
    by = {s: sum(r["status"] == s for r in rows) for s in sorted(STATUSES)}
    print(f"fmea: {len(rows)} rows ok ({', '.join(f'{k} {v}' for k, v in by.items())})")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
